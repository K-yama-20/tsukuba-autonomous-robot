"""Sensor driver settings for ND-14 (hesai_ros_driver, XT-32) and ND-15 (adi_imu_driver, ADIS16607-2). No ROS dependency.

Design: design/model.yaml ND-14 / ND-15, IFD-21 / IFD-22, PRM-50..56 (REV-030, REV-031).
- Hesai: the driver reads one YAML file (`config_path`). It is built from the UPSTREAM template (installed
  share/hesai_ros_driver/config/config.yaml) with only the Gouda keys replaced: device/host IP, UDP/PTC port, timestamp type
  (from design/generated/params/hesai_ros_driver.yaml, trial file only in stub tests), source_type = real-time, and the frame /
  topic of IFD-21. Every other template value is kept as it is (no silent changes).
- IMU: ROS parameters from design/generated/params/adi_imu_driver.yaml plus frame_id (IFD-22) and publish_tf=false (TF has a
  single owner, ND-13: RQ-I004). The driver's own default rate must not be used silently: without `rate` the IMU is not started.
A missing value is reported, never filled in (RQ-I076, CLAUDE.md 1.5).
"""
from __future__ import annotations

import os
from typing import Optional

import yaml

# Interface names from the design (IFD-21 / IFD-22). These are names, not settings.
LIDAR_FRAME = 'xt32_link'
LIDAR_TOPIC = 'sensors/xt32/points'
IMU_FRAME = 'imu_link'
IMU_TOPIC = 'sensors/imu/data'
IMU_DRIVER_TOPIC = 'imu/data_raw'      # adi_imu_tr_driver_ros2 publishes here (remapped to IMU_TOPIC)
HESAI_SOURCE_REALTIME = 1              # upstream config.yaml: "1: real-time lidar connection" (protocol constant, not a vehicle value)

HESAI_KEYS = ('device_ip_address', 'host_ip_address', 'udp_port', 'ptc_port', 'use_timestamp_type')   # PRM-50, 51, 52, 53, 55
IMU_KEYS = ('device', 'rate')                                                                      # PRM-54, 56


def read_node_params(params_dir: str, node: str, trial: bool) -> dict:
    """ros__parameters of <node>.yaml, overlaid with <node>.trial.yaml only when trial (stub tests; never the vehicle)."""
    out = {}
    for name in [f'{node}.yaml'] + ([f'{node}.trial.yaml'] if trial else []):
        path = os.path.join(params_dir, name)
        if os.path.isfile(path):
            with open(path, encoding='utf-8') as f:
                doc = yaml.safe_load(f) or {}
            out.update(((doc.get(node) or {}).get('ros__parameters')) or {})
    return out


def hesai_config(template: dict, params: dict) -> tuple:
    """Return (config dict, missing keys). The template is the upstream config.yaml parsed; it is not modified."""
    missing = [k for k in HESAI_KEYS if params.get(k) is None]
    cfg = yaml.safe_load(yaml.safe_dump(template))    # deep copy
    lidar = cfg['lidar'][0]
    drv = lidar['driver']; udp = drv['lidar_udp_type']; ros = lidar['ros']
    drv['source_type'] = HESAI_SOURCE_REALTIME
    for k in ('device_ip_address', 'host_ip_address', 'udp_port', 'ptc_port'):
        if params.get(k) is not None: udp[k] = params[k]
    if params.get('use_timestamp_type') is not None: drv['use_timestamp_type'] = int(params['use_timestamp_type'])
    ros['ros_frame_id'] = LIDAR_FRAME
    ros['ros_send_point_cloud_topic'] = LIDAR_TOPIC
    return cfg, missing


def write_hesai_config(template_path: str, params: dict, out_path: str) -> list:
    """Write the driver config; returns the missing keys (the file is written only when nothing is missing)."""
    with open(template_path, encoding='utf-8') as f:
        template = yaml.safe_load(f)
    cfg, missing = hesai_config(template, params)
    if missing:
        return missing
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('# GENERATED by gouda_core.sensor_config from the upstream hesai_ros_driver config.yaml and design/generated/params/hesai_ros_driver.yaml\n')
        yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True)
    return []


def imu_parameters(params: dict) -> tuple:
    """Return (ROS parameter dict for adis_rcv_bin_node, missing keys)."""
    missing = [k for k in IMU_KEYS if params.get(k) is None]
    p = {k: params[k] for k in IMU_KEYS if params.get(k) is not None}
    if 'rate' in p: p['rate'] = float(p['rate'])
    p.update({'frame_id': IMU_FRAME, 'publish_tf': False})
    return p, missing


def find_template(share_dir: Optional[str]) -> Optional[str]:
    if not share_dir: return None
    path = os.path.join(share_dir, 'config', 'config.yaml')
    return path if os.path.isfile(path) else None
