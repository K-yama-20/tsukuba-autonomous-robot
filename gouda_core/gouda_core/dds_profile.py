"""Fast DDS profile of every Gouda process (ND-01; REV-144, DEC-279 plan a). No ROS dependency.

The point cloud of IFD-21 (about 1.66 MB per message, 10 Hz) does not fit the default shared-memory segment, so it goes over
UDP. With the default socket receive buffer a BEST_EFFORT subscriber (pcl_ros CropBox of ND-07, the monitor) got 0..8 of
about 100 clouds in 10 s; with a larger buffer it got 75 (VM, 2026-10-22, 第115便). The profile written here:
- keeps the shared-memory transport with its default segment (the larger segment is a separate question, DEC-138);
- uses UDPv4 with the receive and send buffers of udp_buffer_bytes (PRM-100, design/generated/params/gouda_dds.yaml).
The kernel caps the buffers at net.core.rmem_max / wmem_max; the value is not raised here (a system setting).
gouda.sh writes the profile into <data_root>/run/ at every start and passes it to the launch (FASTRTPS_DEFAULT_PROFILES_FILE),
so every node, the driver processes and the child launches started by the nodes use it. A missing value stops the start;
nothing is filled in (RQ-I076, CLAUDE.md 1.5).

    python3 -m gouda_core.dds_profile <params_dir> <output xml>
"""
from __future__ import annotations

import os
import sys

from gouda_core.sensor_config import read_node_params

NODE = 'gouda_dds'          # design/generated/params/gouda_dds.yaml (target of PRM-100)
KEY = 'udp_buffer_bytes'    # PRM-100


def render(buffer_bytes: int) -> str:
    """The profile text. The shared-memory transport is declared without a segment size (Fast DDS default)."""
    if isinstance(buffer_bytes, bool) or not isinstance(buffer_bytes, int) or buffer_bytes <= 0:
        raise ValueError(f'{KEY} (PRM-100) must be a positive integer, got {buffer_bytes!r}')
    return f'''<?xml version="1.0" encoding="UTF-8" ?>
<!-- GENERATED by gouda_core.dds_profile from design/generated/params/{NODE}.yaml at gouda.sh start; do not edit (REV-144, DEC-279). -->
<profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <transport_descriptors>
    <transport_descriptor>
      <transport_id>gouda_shm</transport_id>
      <type>SHM</type>
    </transport_descriptor>
    <transport_descriptor>
      <transport_id>gouda_udp</transport_id>
      <type>UDPv4</type>
      <receiveBufferSize>{buffer_bytes}</receiveBufferSize>
      <sendBufferSize>{buffer_bytes}</sendBufferSize>
    </transport_descriptor>
  </transport_descriptors>
  <participant profile_name="gouda_participant" is_default_profile="true">
    <rtps>
      <userTransports>
        <transport_id>gouda_shm</transport_id>
        <transport_id>gouda_udp</transport_id>
      </userTransports>
      <useBuiltinTransports>false</useBuiltinTransports>
    </rtps>
  </participant>
</profiles>
'''


def write(params_dir: str, out_path: str) -> str:
    """Write the profile; returns '' or the reason it was not written. Trial values are never read (gouda.sh only)."""
    value = read_node_params(params_dir, NODE, trial=False).get(KEY)
    if value is None:
        return f'{KEY} (PRM-100) is unresolved or missing in {os.path.join(params_dir, NODE + ".yaml")}'
    try:
        text = render(value)
    except ValueError as e:
        return str(e)
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(text)
    return ''


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2:
        print('usage: python3 -m gouda_core.dds_profile <params_dir> <output xml>', file=sys.stderr)
        return 2
    why = write(argv[0], argv[1])
    if why:
        print(f'Fast DDS profile not written: {why}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
